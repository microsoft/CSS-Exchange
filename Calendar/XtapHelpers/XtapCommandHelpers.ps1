function ConvertTo-XtapLiteral {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory = $false)]
        [AllowNull()]
        [string]$Value
    )

    # PowerShell treats the typographic single quotes as quote characters, so escape them as well.
    $escaped = $Value -replace "([\u2018\u2019\u201A\u201B])", '$1$1'
    $escaped = $escaped -replace "[\r\n]+", " "
    return ConvertTo-CalendarDiagnosticCommandLineValue -Value $escaped
}

function ConvertTo-XtapComment {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory = $false)]
        [AllowNull()]
        [string]$Value
    )

    return ("$Value" -replace "[\r\n]+", " ")
}

function Get-XtapCommandScriptHeader {
    [CmdletBinding()]
    [OutputType([string[]])]
    param(
        [string]$Title,
        [string]$RunName,
        [string[]]$Description
    )

    $header = @(
        "# $Title",
        "# Generated by CrossTenantAccessPolicyCalendarValidation.ps1 for run '$(ConvertTo-XtapComment -Value $RunName)' on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss').",
        "# Review every command before you run it. Nothing in this file runs until you run it."
    )
    foreach ($line in $Description) {
        $header += "# $line"
    }

    return $header
}

<#
.SYNOPSIS
    Generates the ready-to-run command scripts for the items that can be migrated to Microsoft 365 Cross-Tenant Access Policy.
.DESCRIPTION
    Follows Parts 2, 3 and 4 of https://learn.microsoft.com/exchange/sharing/migrate-to-m365-xtap
    Only Eligible items are included. Values that the script can't know (a partner tenant ID that wasn't looked up,
    or the security group for a scoped relationship) are written as <placeholders>, and the generated commands stop
    with an error if a placeholder isn't replaced.
.OUTPUTS
    An ordered hashtable of file name to script text. A file is only returned if it contains commands.
#>
function Get-XtapCommandScript {
    [CmdletBinding()]
    [OutputType([System.Collections.Specialized.OrderedDictionary])]
    param(
        [Parameter(Mandatory = $false)]
        [AllowNull()]
        [AllowEmptyCollection()]
        [object[]]$OrganizationRelationshipAnalysis,

        [Parameter(Mandatory = $false)]
        [AllowNull()]
        [AllowEmptyCollection()]
        [object[]]$AvailabilityAddressSpaceAnalysis,

        [Parameter(Mandatory = $false)]
        [AllowNull()]
        [AllowEmptyCollection()]
        [object[]]$SharingPolicyAnalysis,

        [Parameter(Mandatory = $false)]
        [string]$RunName = "Calendar Validation",

        [Parameter(Mandatory = $false)]
        [string]$Organization
    )

    $orgArg = ""
    if (-not [string]::IsNullOrWhiteSpace($Organization)) {
        $orgArg = " -Organization $(ConvertTo-XtapLiteral -Value $Organization)"
    }

    $orgRows = @(@($OrganizationRelationshipAnalysis) | Where-Object { $null -ne $_ -and $_.Status -eq "Eligible" })
    $aasRows = @(@($AvailabilityAddressSpaceAnalysis) | Where-Object { $null -ne $_ -and $_.Status -eq "Eligible" })
    $allSharingRows = @(@($SharingPolicyAnalysis) | Where-Object {
            $null -ne $_ -and ($null -eq $_.AssignedMailboxCount -or $_.AssignedMailboxCount -gt 0)
        })
    $sharingRows = @($allSharingRows | Where-Object { $_.Status -eq "Eligible" })

    $trustTenants = New-Object System.Collections.Generic.List[string]
    $freeBusyCalls = New-Object System.Collections.Generic.List[string]
    $mailTipsCalls = New-Object System.Collections.Generic.List[string]
    $sharingCalls = New-Object System.Collections.Generic.List[string]
    $seenCalls = @{}

    function Add-UniqueCall {
        param($List, [string]$Key, [string[]]$Line)
        if (-not $seenCalls.ContainsKey($Key)) {
            $seenCalls[$Key] = $true
            foreach ($l in $Line) { $List.Add($l) }
        }
    }

    foreach ($row in $orgRows) {
        $tenantIds = @("$($row.PartnerTenantIds)" -split ";" | Where-Object { $_ -match $Script:XtapGuidPattern })
        if ($tenantIds.Count -eq 0) {
            $tenantIds = @("<PartnerTenantId for $($row.DomainNames)>")
        }

        foreach ($tenantId in $tenantIds) {
            if (-not $trustTenants.Contains($tenantId)) { $trustTenants.Add($tenantId) }
            $tenantLiteral = ConvertTo-XtapLiteral -Value $tenantId
            $comment = "# Organization Relationship '$(ConvertTo-XtapComment -Value $row.OrganizationRelationship)' ($(ConvertTo-XtapComment -Value $row.DomainNames))"

            foreach ($feature in @(
                    @{ Capability = $row.FreeBusyCapability; Scoped = $row.FreeBusyScoped; Scope = $row.FreeBusyAccessScope; List = $freeBusyCalls },
                    @{ Capability = $row.MailTipsCapability; Scoped = $row.MailTipsScoped; Scope = $row.MailTipsAccessScope; List = $mailTipsCalls })) {
                if ([string]::IsNullOrEmpty($feature.Capability)) { continue }
                $resourceType = "user"
                $resourceId = "All"
                $lines = @($comment)
                if ($feature.Scoped) {
                    $resourceType = "group"
                    $resourceId = "<SecurityGroupObjectId for scope $($feature.Scope)>"
                    $lines += "# The scope [$(ConvertTo-XtapComment -Value $feature.Scope)] was set. Create a mail-enabled security group with the same members and put its object ID below."
                }

                $lines += "Add-XtapCapability -PartnerTenantId $tenantLiteral -Capability $(ConvertTo-XtapLiteral -Value $feature.Capability) -ResourceType $resourceType -ResourceId $(ConvertTo-XtapLiteral -Value $resourceId) -ODataPrefix 'microsoft.graph.'"
                Add-UniqueCall -List $feature.List -Key "$tenantId|$($feature.Capability)|$resourceId" -Line $lines
            }
        }
    }

    foreach ($row in $aasRows) {
        $tenantId = "$($row.TargetTenantId)"
        if (-not $trustTenants.Contains($tenantId)) { $trustTenants.Add($tenantId) }
        Add-UniqueCall -List $freeBusyCalls -Key "$tenantId|$($row.RecommendedCapability)|All" -Line @(
            "# Availability Address Space '$(ConvertTo-XtapComment -Value $row.ForestName)'",
            "Add-XtapCapability -PartnerTenantId $(ConvertTo-XtapLiteral -Value $tenantId) -Capability $(ConvertTo-XtapLiteral -Value $row.RecommendedCapability) -ResourceType user -ResourceId 'All' -ODataPrefix 'microsoft.graph.'")
    }

    $sharingRequests = [ordered]@{}
    foreach ($row in $sharingRows) {
        $resourceId = "<SecurityGroupObjectId for Sharing Policy $($row.SharingPolicy)>"
        $lines = @(
            "# Sharing Policy '$(ConvertTo-XtapComment -Value $row.SharingPolicy)' rule '$(ConvertTo-XtapComment -Value $row.Rule)'",
            "# Put the object ID of a security group containing only the mailboxes using this policy below, including inherited default-policy assignments.")

        $tenantArgument = ""
        $tenantKey = "default"
        if ($row.RuleType -eq "Domain-specific") {
            $tenantId = "$($row.PartnerTenantId)"
            if (-not $trustTenants.Contains($tenantId)) { $trustTenants.Add($tenantId) }
            $tenantArgument = "-PartnerTenantId $(ConvertTo-XtapLiteral -Value $tenantId) "
            $tenantKey = $tenantId
        }

        $key = "$tenantKey|$($row.RecommendedCapability)"
        if (-not $sharingRequests.Contains($key)) {
            $sharingRequests[$key] = @{ TenantArgument = $tenantArgument; Capability = $row.RecommendedCapability; ResourceIds = @(); Comments = @() }
        }
        $sharingRequests[$key].ResourceIds += $resourceId
        $sharingRequests[$key].Comments += $lines
    }
    foreach ($request in $sharingRequests.Values) {
        foreach ($comment in @($request.Comments | Select-Object -Unique)) { $sharingCalls.Add($comment) }
        $resourceLiterals = @($request.ResourceIds | Select-Object -Unique | ForEach-Object { ConvertTo-XtapLiteral -Value $_ }) -join ", "
        $sharingCalls.Add("Add-XtapCapability $($request.TenantArgument)-Capability $(ConvertTo-XtapLiteral -Value $request.Capability) -ResourceType group -ResourceId $resourceLiterals -ODataPrefix '#microsoft.graph.'")
    }

    $scripts = [ordered]@{}
    $hasWildcardSharing = @($sharingRows | Where-Object { $_.RuleType -eq "Wildcard" }).Count -gt 0
    $capabilityHelpers = @(
        'function Get-XtapCapability {',
        '    param([string]$PartnerTenantId, [string]$Capability)',
        '    $items = if ($PartnerTenantId -eq "default") {',
        '        @(Get-MgPolicyCrossTenantAccessPolicyDefaultM365Capability -All -ErrorAction Stop)',
        '    } else {',
        '        @(Get-MgPolicyCrossTenantAccessPolicyPartnerM365Capability -CrossTenantAccessPolicyConfigurationPartnerTenantId $PartnerTenantId -All -ErrorAction Stop)',
        '    }',
        '    $matches = @($items | Where-Object { $_.Name -eq $Capability })',
        '    if ($matches.Count -gt 1) { throw "More than one $Capability capability was returned for $PartnerTenantId. Review manually." }',
        '    if ($matches.Count -eq 1) { return $matches[0] }',
        '}',
        '',
        'function Get-XtapAccessFingerprint {',
        '    param($Access)',
        '    if ($Access.IsAllowed -isnot [bool] -or $null -eq $Access.ResourceScopes) {',
        '        throw "The capability inbound access could not be read. Review manually before making changes."',
        '    }',
        '    $scopes = @{}',
        '    foreach ($name in @("included", "excluded")) {',
        '        $scopes[$name] = @($Access.ResourceScopes.$name | Where-Object { -not [string]::IsNullOrWhiteSpace($_.ResourceId) } | ForEach-Object {',
        '            "$($_.ResourceType):$($_.ResourceId)".ToLowerInvariant()',
        '        } | Sort-Object -Unique)',
        '    }',
        '    [ordered]@{ isAllowed = $Access.IsAllowed; included = $scopes.included; excluded = $scopes.excluded } | ConvertTo-Json -Depth 10 -Compress',
        '}',
        '',
        'function Read-XtapMigrationState {',
        '    param([switch]$Required)',
        '    $tenantId = [string](Get-MgContext).TenantId',
        '    if ($tenantId -notmatch ''^[0-9a-fA-F]{8}-([0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12}$'') { throw "Cannot identify the connected Graph tenant." }',
        '    if (-not (Test-Path -LiteralPath $script:migrationStatePath)) {',
        '        if ($Required) { throw "The Part 2 capability backup is missing: $script:migrationStatePath. Do not remove capabilities without the original backup." }',
        '        return [PSCustomObject]@{ SchemaVersion = 1; TenantId = $tenantId; RollbackCompleted = $false; Capabilities = @() }',
        '    }',
        '    $state = Get-Content -LiteralPath $script:migrationStatePath -Raw -Encoding UTF8 -ErrorAction Stop | ConvertFrom-Json -ErrorAction Stop',
        '    if ($state.SchemaVersion -ne 1 -or $state.TenantId -ne $tenantId -or $state.Capabilities -isnot [array] -or $state.RollbackCompleted -isnot [bool]) {',
        '        throw "The Part 2 capability backup is invalid or belongs to a different tenant. Keep the original backup and connect to the correct tenant."',
        '    }',
        '    foreach ($entry in $state.Capabilities) {',
        '        if ($entry.Existed -isnot [bool] -or $entry.Created -isnot [bool] -or [string]::IsNullOrWhiteSpace($entry.Capability) -or [string]::IsNullOrWhiteSpace($entry.PartnerTenantId) -or ($entry.Created -and $entry.CreatedName -ine $entry.Capability)) {',
        '            throw "The Part 2 capability backup contains an invalid entry. Review manually."',
        '        }',
        '    }',
        '    return $state',
        '}',
        '',
        'function Save-XtapMigrationState {',
        '    $temporaryPath = "$script:migrationStatePath.tmp"',
        '    try {',
        '        ConvertTo-Json -InputObject $script:migrationState -Depth 30 -ErrorAction Stop | Set-Content -LiteralPath $temporaryPath -Encoding UTF8 -ErrorAction Stop',
        '        if (Test-Path -LiteralPath $script:migrationStatePath) {',
        '            [System.IO.File]::Replace($temporaryPath, $script:migrationStatePath, [NullString]::Value)',
        '        } else {',
        '            [System.IO.File]::Move($temporaryPath, $script:migrationStatePath)',
        '        }',
        '    } finally {',
        '        if (Test-Path -LiteralPath $temporaryPath) { Remove-Item -LiteralPath $temporaryPath -ErrorAction Stop }',
        '    }',
        '}',
        '')

    if ($trustTenants.Count -gt 0 -or $sharingCalls.Count -gt 0) {
        $lines = New-Object System.Collections.Generic.List[string]
        foreach ($line in (Get-XtapCommandScriptHeader -Title "Part 2 - Create the Microsoft 365 Cross-Tenant Access Policies" -RunName $RunName -Description @(
                    "https://learn.microsoft.com/exchange/sharing/migrate-to-m365-xtap#part-2--configure-your-new-microsoft-365-cross-tenant-access-policies",
                    "Requires the Microsoft Graph PowerShell SDK. Creating the trust needs Global Administrator.",
                    "Authentication failures stop this script before any policy changes. Resolve the error before rerunning Part 2.",
                    "Capability baselines are saved beside this script in XTAP_Part2_CapabilityBackup.json before creation. Keep this file for rollback.",
                    "Pre-existing capabilities are left unchanged and stop automatic migration; review and merge their scopes manually.",
                    "Do not run Part 2 concurrently or delete its backup to bypass a conflict. After rollback, generate a fresh assessment for a new migration.",
                    "XTAP is an inbound setting. For two-way sharing the external organization must create complementary policies.",
                    "The Microsoft 365 cross-tenant access policy cmdlets can change. Confirm the cmdlet names against the documentation if one isn't found."))) {
            $lines.Add($line)
        }

        $lines.Add("")
        $tenantArg = ""
        if (-not [string]::IsNullOrWhiteSpace($Organization)) {
            $tenantArg = " -TenantId $(ConvertTo-XtapLiteral -Value $Organization)"
        }

        $lines.Add("Connect-MgGraph -Scopes `"Policy.Read.All,Policy.ReadWrite.CrossTenantAccess,Policy.ReadWrite.CrossTenantCapability`"$tenantArg -ContextScope Process -ErrorAction Stop")
        $lines.Add("")
        foreach ($line in $capabilityHelpers) { $lines.Add($line) }
        $lines.Add('$script:migrationStatePath = Join-Path -Path $PSScriptRoot -ChildPath "XTAP_Part2_CapabilityBackup.json"')
        $lines.Add('$script:migrationState = Read-XtapMigrationState')
        $lines.Add('if ($script:migrationState.RollbackCompleted) { throw "This migration was rolled back. Generate a fresh assessment and scripts before migrating again." }')
        $lines.Add("")
        foreach ($line in @(
                'function Assert-XtapInput {',
                '    param([string]$Value, [string]$Name)',
                '    if ([string]::IsNullOrWhiteSpace($Value) -or $Value -match ''^<.*>$'') {',
                '        throw "Replace the $Name placeholder with a real value before you run this command."',
                '    }',
                '}',
                '',
                'function Set-XtapPartnerTrust {',
                '    param([string]$PartnerTenantId)',
                '    Assert-XtapInput -Value $PartnerTenantId -Name "partner tenant ID"',
                '    $inbound = @{ users = @{ accessType = "allowed"; targets = @(@{ target = "AllUsers"; targetType = "user" }) } }',
                '    $existing = $null',
                '    try {',
                '        $existing = Get-MgPolicyCrossTenantAccessPolicyPartner -CrossTenantAccessPolicyConfigurationPartnerTenantId $PartnerTenantId -ErrorAction Stop',
                '    } catch {',
                '        Write-Verbose "No existing partner policy for $PartnerTenantId."',
                '    }',
                '    if ($null -eq $existing) {',
                '        New-MgPolicyCrossTenantAccessPolicyPartner -BodyParameter @{ tenantId = $PartnerTenantId; m365CollaborationInbound = $inbound } -ErrorAction Stop | Out-Null',
                '        Write-Host "Created the Microsoft 365 Collaboration trust for $PartnerTenantId."',
                '    } elseif ($null -eq $existing.AdditionalProperties.m365CollaborationInbound) {',
                '        Update-MgPolicyCrossTenantAccessPolicyPartner -CrossTenantAccessPolicyConfigurationPartnerTenantId $PartnerTenantId -BodyParameter @{ m365CollaborationInbound = $inbound } -ErrorAction Stop | Out-Null',
                '        Write-Host "Enabled the Microsoft 365 Collaboration trust for $PartnerTenantId."',
                '    } else {',
                '        Write-Warning "A Microsoft 365 Collaboration trust already exists for $PartnerTenantId. It was left unchanged. Confirm it allows the users you expect."',
                '    }',
                '}',
                '',
                'function Add-XtapCapability {',
                '    param([string]$PartnerTenantId, [string]$Capability, [string]$ResourceType, [string[]]$ResourceId, [string]$ODataPrefix)',
                '    if ($PSBoundParameters.ContainsKey("PartnerTenantId")) { Assert-XtapInput -Value $PartnerTenantId -Name "partner tenant ID" }',
                '    if ($ResourceId.Count -eq 0) { throw "At least one resource scope is required." }',
                '    $included = @(',
                '        foreach ($id in @($ResourceId | Sort-Object -Unique)) {',
                '            Assert-XtapInput -Value $id -Name "security group"',
                '            @{ resourceId = $id; resourceType = $ResourceType }',
                '        }',
                '    )',
                '    $body = @{',
                '        "@odata.type" = "$ODataPrefix$Capability"',
                '        inboundAccess = @{',
                '            isAllowed = $true',
                '            resourceScopes = @{ included = $included; excluded = @() }',
                '        }',
                '    }',
                '    $target = if ($PSBoundParameters.ContainsKey("PartnerTenantId")) { $PartnerTenantId } else { "the default policy" }',
                '    $targetId = if ($PSBoundParameters.ContainsKey("PartnerTenantId")) { $PartnerTenantId } else { "default" }',
                '    $existing = Get-XtapCapability -PartnerTenantId $targetId -Capability $Capability',
                '    $entries = @($script:migrationState.Capabilities | Where-Object { $_.PartnerTenantId -eq $targetId -and $_.Capability -eq $Capability })',
                '    if ($entries.Count -gt 1) { throw "Duplicate capability backup entries for $Capability on $target. Review manually." }',
                '    if ($entries.Count -eq 0) {',
                '        $entry = [PSCustomObject]@{ PartnerTenantId = $targetId; Capability = $Capability; Existed = ($null -ne $existing); Created = $false; CreatedName = $null; OriginalInboundAccess = $existing.InboundAccess; AppliedInboundAccess = $body.inboundAccess }',
                '        $script:migrationState.Capabilities += $entry',
                '        Save-XtapMigrationState',
                '    } else {',
                '        $entry = $entries[0]',
                '    }',
                '    if ($entry.Existed) { throw "A pre-existing $Capability capability for $target was left unchanged. Review its access and merge scopes manually before migrating." }',
                '    $expected = Get-XtapAccessFingerprint -Access $entry.AppliedInboundAccess',
                '    if ($expected -ne (Get-XtapAccessFingerprint -Access $body.inboundAccess)) { throw "The requested $Capability scope differs from this run''s backup. Review manually." }',
                '    if ($null -ne $existing) {',
                '        if (-not $entry.Created) { throw "The previous creation of $Capability for $target has an uncertain outcome. Review manually; do not adopt or remove it automatically." }',
                '        if ($expected -ne (Get-XtapAccessFingerprint -Access $existing.InboundAccess)) { throw "$Capability for $target changed after this run began. Review manually." }',
                '        Write-Host "$Capability for $target already matches this run. The original backup was preserved."',
                '        return',
                '    }',
                '    try {',
                '        if ($PSBoundParameters.ContainsKey("PartnerTenantId")) {',
                '            $created = New-MgPolicyCrossTenantAccessPolicyPartnerM365Capability -CrossTenantAccessPolicyConfigurationPartnerTenantId $PartnerTenantId -BodyParameter $body -ErrorAction Stop',
                '        } else {',
                '            $created = New-MgPolicyCrossTenantAccessPolicyDefaultM365Capability -BodyParameter $body -ErrorAction Stop',
                '        }',
                '        if ($created.Name -ine $Capability) { throw "Graph did not return the expected created capability. Review the creation outcome manually." }',
                '        $entry.CreatedName = [string]$created.Name',
                '        $entry.Created = $true',
                '        Save-XtapMigrationState',
                '        Write-Host "Created $Capability for $target."',
                '    } catch {',
                '        throw "Failed to create $Capability for $($target): $($_.Exception.Message)"',
                '    }',
                '}',
                '') ) {
            $lines.Add($line)
        }

        $lines.Add("# Microsoft 365 Collaboration trust (once for each external organization)")
        foreach ($tenantId in $trustTenants) {
            if ($tenantId -match "^<" -or $tenantId -match $Script:XtapGuidPattern) {
                $lines.Add("Set-XtapPartnerTrust -PartnerTenantId $(ConvertTo-XtapLiteral -Value $tenantId)")
            }
        }
        if ($hasWildcardSharing) {
            $lines.Add("")
            $lines.Add("# Wildcard calendar sharing uses default capabilities but does not establish collaboration trust.")
            $lines.Add("# Manually inspect Get-MgPolicyCrossTenantAccessPolicyDefault and each intended partner's Get-MgPolicyCrossTenantAccessPolicyPartner result.")
            $lines.Add("# Verify effective m365CollaborationInbound access and user/group scopes, including partner overrides, for every intended Microsoft 365 partner.")
            $lines.Add("# Do not broadly enable default collaboration trust just to migrate a wildcard Sharing Policy.")
            $lines.Add('Write-Warning "Wildcard capabilities have no effect without effective Microsoft 365 Collaboration trust. Manually verify trust and sharing before disabling any legacy policy."')
        }

        foreach ($section in @(
                @{ Title = "Free/Busy"; List = $freeBusyCalls },
                @{ Title = "MailTips"; List = $mailTipsCalls },
                @{ Title = "Calendar Sharing"; List = $sharingCalls })) {
            if ($section.List.Count -gt 0) {
                $lines.Add("")
                $lines.Add("# $($section.Title)")
                foreach ($line in $section.List) { $lines.Add($line) }
            }
        }

        $scripts["XTAP_Part2_CreatePolicies.ps1"] = $lines -join "`r`n"
    }

    # Preserve other functionality while turning off only the sharing settings migrated to XTAP.
    $disableOrgRows = @($orgRows | Where-Object { -not ($_.HasMailboxMoveAndSharing -or $_.HasAdditionalFunctionalitiesAndSharing) })
    $sharingOnlyOrgRows = @($orgRows | Where-Object { $_.HasMailboxMoveAndSharing -or $_.HasAdditionalFunctionalitiesAndSharing })
    $policyNames = @($allSharingRows | Select-Object -ExpandProperty SharingPolicy -Unique)
    $disablePolicies = @($policyNames | Where-Object {
            $name = $_
            $rows = @($allSharingRows | Where-Object { $_.SharingPolicy -eq $name })
            $rows[0].Enabled -and @($rows | Where-Object { $_.Status -ne "Eligible" }).Count -eq 0
        })
    $partialPolicies = @($policyNames | Where-Object {
            $name = $_
            $rows = @($allSharingRows | Where-Object { $_.SharingPolicy -eq $name })
            $rows[0].Enabled -and @($rows | Where-Object { $_.Status -eq "Eligible" }).Count -gt 0 -and
            @($rows | Where-Object { $_.Status -ne "Eligible" }).Count -gt 0
        })

    $hasLegacyTestCommands = $disableOrgRows.Count + $sharingOnlyOrgRows.Count + $aasRows.Count + $disablePolicies.Count -gt 0
    if ($hasLegacyTestCommands -or $scripts.Contains("XTAP_Part2_CreatePolicies.ps1")) {
        $testLines = New-Object System.Collections.Generic.List[string]
        $rollbackLines = New-Object System.Collections.Generic.List[string]
        $cleanupLines = New-Object System.Collections.Generic.List[string]

        foreach ($line in (Get-XtapCommandScriptHeader -Title "Part 3 - Disable the existing configuration to test XTAP" -RunName $RunName -Description @(
                    "https://learn.microsoft.com/exchange/sharing/migrate-to-m365-xtap#part-3--test-functionality",
                    "Run Part 2 first. Organization Relationships and Availability Address Spaces take precedence over XTAP.",
                    "Applicable XTAP calendar sharing capabilities take precedence over Sharing Policies; calendar sharing can be tested with those policies enabled.",
                    "Manually verify effective Microsoft 365 Collaboration trust, including default settings, partner overrides and user/group scopes, and test the replacement policies.",
                    "Only after verification, run this script with -ReplacementPoliciesVerified. This confirmation does not configure or automatically validate trust.",
                    "Coordinate with the external organization administrators. Both organizations must test at the same time.",
                    "Connect to Exchange Online PowerShell first (Connect-ExchangeOnline). To undo, run XTAP_Part3_Rollback.ps1."))) {
            $testLines.Add($line)
        }

        foreach ($line in (Get-XtapCommandScriptHeader -Title "Part 3 - Roll back: restore legacy sharing and remove this run's new capabilities" -RunName $RunName -Description @(
                    "Connect to Exchange Online PowerShell first (Connect-ExchangeOnline). Microsoft Graph authentication is also required.",
                    "Keep XTAP_Part2_CapabilityBackup.json beside this script. Only capabilities absent before this run and still matching its recorded access are removed.",
                    "Pre-existing capabilities are never overwritten by Part 2 and are left unchanged here. Drift or missing backups stop rollback for manual review.",
                    "Partner policies and collaboration trust created or updated in Part 2 are retained to avoid disrupting other workloads; review trust cleanup separately.",
                    "Legacy settings are restored before removing capabilities. Applicable pre-existing XTAP capabilities will still take precedence over Sharing Policies.",
                    "Only Availability Address Spaces removed by this run are restored from the Part 3 backups. Untouched spaces are skipped.",
                    "Restoration can be retried after partial execution. Missing backups for absent spaces or conflicting existing configuration stop rollback for manual review."))) {
            $rollbackLines.Add($line)
        }

        foreach ($line in (Get-XtapCommandScriptHeader -Title "Part 4 - Remove the old configuration" -RunName $RunName -Description @(
                    "https://learn.microsoft.com/exchange/sharing/migrate-to-m365-xtap#part-4--clean-up-old-configurations",
                    "Only run this after both organizations confirmed that Free/Busy, MailTips and calendar sharing work with XTAP.",
                    "All configuration-changing commands below are commented out. Running this file unchanged makes no changes.",
                    "To perform cleanup, deliberately uncomment the required commands or copy and run them individually.",
                    "Deletion is permanent. Keep the collected JSON bundle and Part 3 rollback script and backups before proceeding.",
                    "Part 3 rollback does not recreate Organization Relationships or Sharing Policies deleted during cleanup.",
                    "Availability Address Spaces were already removed (and backed up) by XTAP_Part3_DisableForTesting.ps1.",
                    "Connect to Exchange Online PowerShell first (Connect-ExchangeOnline)."))) {
            $cleanupLines.Add($line)
        }

        foreach ($line in @(
                '',
                'param([switch]$ReplacementPoliciesVerified)',
                '',
                'if (-not $ReplacementPoliciesVerified) {',
                '    throw "Manually verify effective Microsoft 365 Collaboration trust and replacement policy functionality before disabling legacy sharing. Then rerun with -ReplacementPoliciesVerified."',
                '}',
                '')) {
            $testLines.Add($line)
        }

        $rollbackLines.Add("")
        $rollbackLines.Add('$ErrorActionPreference = "Stop"')
        $rollbackLines.Add("Connect-MgGraph -Scopes `"Policy.Read.All,Policy.ReadWrite.CrossTenantCapability`"$tenantArg -ContextScope Process -ErrorAction Stop")
        foreach ($line in $capabilityHelpers) { $rollbackLines.Add($line) }
        foreach ($line in @(
                '$script:migrationStatePath = Join-Path -Path $PSScriptRoot -ChildPath "XTAP_Part2_CapabilityBackup.json"',
                '$script:migrationState = Read-XtapMigrationState -Required',
                'if ($script:migrationState.RollbackCompleted) { Write-Host "This migration was already rolled back."; return }',
                '$capabilitiesToRemove = @(',
                '    foreach ($entry in $script:migrationState.Capabilities) {',
                '        if ($entry.Existed) { continue }',
                '        $current = Get-XtapCapability -PartnerTenantId $entry.PartnerTenantId -Capability $entry.Capability',
                '        if ($null -eq $current) { continue }',
                '        if (-not $entry.Created) { throw "The creation of $($entry.Capability) has an uncertain outcome. No rollback changes were made. Review manually." }',
                '        if ((Get-XtapAccessFingerprint -Access $current.InboundAccess) -ne (Get-XtapAccessFingerprint -Access $entry.AppliedInboundAccess)) {',
                '            throw "$($entry.Capability) for $($entry.PartnerTenantId) changed after migration. No rollback changes were made. Review manually."',
                '        }',
                '        $entry',
                '    }',
                ')')) {
            $rollbackLines.Add($line)
        }

        if ($disableOrgRows.Count -gt 0) {
            foreach ($list in @($testLines, $rollbackLines, $cleanupLines)) { $list.Add(""); $list.Add("# Organization Relationships") }
            foreach ($row in $disableOrgRows) {
                $nameLiteral = ConvertTo-XtapLiteral -Value $row.OrganizationRelationship
                $testLines.Add("Set-OrganizationRelationship -Identity $nameLiteral -Enabled `$false$orgArg")
                $rollbackLines.Add("Set-OrganizationRelationship -Identity $nameLiteral -Enabled `$true$orgArg")
                $cleanupLines.Add("# Remove-OrganizationRelationship -Identity $nameLiteral -Confirm:`$true$orgArg")
            }
        }

        if ($sharingOnlyOrgRows.Count -gt 0) {
            $note = "# Additional functionality must be preserved, so the relationship stays. Only its Free/Busy and MailTips settings are changed."
            foreach ($list in @($testLines, $rollbackLines, $cleanupLines)) {
                $list.Add("")
                $list.Add("# Organization Relationships with additional functionality")
                $list.Add($note)
            }

            foreach ($row in $sharingOnlyOrgRows) {
                $nameLiteral = ConvertTo-XtapLiteral -Value $row.OrganizationRelationship
                $offSettings = ""
                $onSettings = ""
                if ($row.FreeBusyAccessEnabled) {
                    $offSettings += " -FreeBusyAccessEnabled `$false"
                    $onSettings += " -FreeBusyAccessEnabled `$true -FreeBusyAccessLevel $(ConvertTo-XtapLiteral -Value $row.FreeBusyAccessLevel)"
                    if ($row.FreeBusyScoped) { $onSettings += " -FreeBusyAccessScope $(ConvertTo-XtapLiteral -Value $row.FreeBusyAccessScope)" }
                }

                if ($row.MailTipsAccessEnabled) {
                    $offSettings += " -MailTipsAccessEnabled `$false"
                    $onSettings += " -MailTipsAccessEnabled `$true -MailTipsAccessLevel $(ConvertTo-XtapLiteral -Value $row.MailTipsAccessLevel)"
                    if ($row.MailTipsScoped) { $onSettings += " -MailTipsAccessScope $(ConvertTo-XtapLiteral -Value $row.MailTipsAccessScope)" }
                }

                $testLines.Add("Set-OrganizationRelationship -Identity $nameLiteral$offSettings$orgArg")
                $rollbackLines.Add("Set-OrganizationRelationship -Identity $nameLiteral$onSettings$orgArg")
                $cleanupLines.Add("# Set-OrganizationRelationship -Identity $nameLiteral$offSettings$orgArg")
            }
        }

        if ($aasRows.Count -gt 0) {
            $availabilityHelpers = @(
                '',
                'function Get-XtapAvailabilityConfiguration {',
                '    param($AddressSpace)',
                '    $configuration = [ordered]@{}',
                '    foreach ($name in @("ForestName", "AccessMethod", "ProxyUrl", "TargetAutodiscoverEpr", "TargetServiceEpr", "TargetTenantId")) {',
                '        $configuration[$name] = [string]$AddressSpace.$name',
                '    }',
                '    return $configuration',
                '}',
                '',
                'function Get-XtapAvailabilityAddressSpace {',
                '    param([string]$ForestName, [string]$Organization)',
                '    $p = @{}',
                '    if (-not [string]::IsNullOrEmpty($Organization)) { $p.Organization = $Organization }',
                '    $items = @(Get-AvailabilityAddressSpace @p -ErrorAction Stop | Where-Object { $_.ForestName -eq $ForestName })',
                '    if ($items.Count -gt 1) { throw "More than one Availability Address Space matches $ForestName. Review manually." }',
                '    if ($items.Count -eq 1) { return $items[0] }',
                '}',
                '',
                'function Save-XtapAvailabilityBackup {',
                '    param([string]$Path, $State)',
                '    $temporaryPath = "$Path.tmp"',
                '    try {',
                '        ConvertTo-Json -InputObject $State -Depth 10 -ErrorAction Stop | Set-Content -LiteralPath $temporaryPath -Encoding UTF8 -ErrorAction Stop',
                '        if (Test-Path -LiteralPath $Path) {',
                '            [System.IO.File]::Replace($temporaryPath, $Path, [NullString]::Value)',
                '        } else {',
                '            [System.IO.File]::Move($temporaryPath, $Path)',
                '        }',
                '    } finally {',
                '        if (Test-Path -LiteralPath $temporaryPath) { Remove-Item -LiteralPath $temporaryPath -ErrorAction Stop }',
                '    }',
                '}',
                '',
                'function Update-XtapAvailabilityAddressSpace {',
                '    param([string]$Path, [string]$ForestName, [string]$Organization, [switch]$Restore)',
                '    $current = Get-XtapAvailabilityAddressSpace -ForestName $ForestName -Organization $Organization',
                '    if (Test-Path -LiteralPath $Path) {',
                '        $state = Get-Content -LiteralPath $Path -Raw -Encoding UTF8 -ErrorAction Stop | ConvertFrom-Json -ErrorAction Stop',
                '        if ($state.SchemaVersion -ne 1 -or $state.ForestName -ne $ForestName -or "$($state.Organization)" -ne "$Organization" -or',
                '            $state.Configuration.ForestName -ne $ForestName -or [string]::IsNullOrWhiteSpace($state.Configuration.AccessMethod) -or',
                '            $state.RemovalAttempted -isnot [bool] -or $state.Removed -isnot [bool] -or $state.Restored -isnot [bool]) {',
                '            throw "The Availability Address Space backup for $ForestName is invalid or belongs to a different organization. Review manually."',
                '        }',
                '    } elseif ($Restore) {',
                '        if ($null -eq $current) { throw "The Availability Address Space backup is missing for $ForestName. Review manually." }',
                '        return',
                '    } else {',
                '        if ($null -eq $current) { throw "Cannot back up the missing Availability Address Space $ForestName. Review manually." }',
                '        $state = [PSCustomObject]@{',
                '            SchemaVersion = 1; ForestName = $ForestName; Organization = "$Organization"',
                '            RemovalAttempted = $false; Removed = $false; Restored = $false',
                '            Configuration = Get-XtapAvailabilityConfiguration -AddressSpace $current',
                '        }',
                '        Save-XtapAvailabilityBackup -Path $Path -State $state',
                '    }',
                '    $expected = Get-XtapAvailabilityConfiguration -AddressSpace $state.Configuration | ConvertTo-Json -Compress',
                '    if ($null -ne $current -and (Get-XtapAvailabilityConfiguration -AddressSpace $current | ConvertTo-Json -Compress) -ne $expected) {',
                '        throw "The Availability Address Space $ForestName configuration conflicts with its backup. Review manually."',
                '    }',
                '    $p = @{}',
                '    if (-not [string]::IsNullOrEmpty($Organization)) { $p.Organization = $Organization }',
                '    if ($Restore) {',
                '        if ($null -ne $current) {',
                '            if ($state.Removed -and -not $state.Restored) {',
                '                $state.Restored = $true',
                '                Save-XtapAvailabilityBackup -Path $Path -State $state',
                '            }',
                '            return',
                '        }',
                '        if ($state.Restored -or -not ($state.RemovalAttempted -or $state.Removed)) {',
                '            throw "No pending removal is recorded for the missing Availability Address Space $ForestName. Review manually."',
                '        }',
                '        foreach ($name in @("ForestName", "AccessMethod", "ProxyUrl", "TargetAutodiscoverEpr", "TargetServiceEpr", "TargetTenantId")) {',
                '            if (-not [string]::IsNullOrEmpty($state.Configuration.$name)) { $p[$name] = $state.Configuration.$name }',
                '        }',
                '        Add-AvailabilityAddressSpace @p -ErrorAction Stop',
                '        $state.Removed = $true',
                '        $state.Restored = $true',
                '        Save-XtapAvailabilityBackup -Path $Path -State $state',
                '        return',
                '    }',
                '    if ($state.Restored) { throw "$ForestName was already restored. Generate a fresh assessment before migrating again." }',
                '    if ($null -eq $current) {',
                '        if (-not ($state.RemovalAttempted -or $state.Removed)) { throw "No removal is recorded for the missing Availability Address Space $ForestName. Review manually." }',
                '        $state.Removed = $true',
                '        Save-XtapAvailabilityBackup -Path $Path -State $state',
                '        return',
                '    }',
                '    if ($state.Removed) { throw "The removed Availability Address Space $ForestName has reappeared. Review manually." }',
                '    $state.RemovalAttempted = $true',
                '    Save-XtapAvailabilityBackup -Path $Path -State $state',
                '    Remove-AvailabilityAddressSpace -Identity $ForestName @p -Confirm:$true -ErrorAction Stop',
                '    $remaining = Get-XtapAvailabilityAddressSpace -ForestName $ForestName -Organization $Organization',
                '    if ($null -eq $remaining) {',
                '        $state.Removed = $true',
                '    } elseif ((Get-XtapAvailabilityConfiguration -AddressSpace $remaining | ConvertTo-Json -Compress) -ne $expected) {',
                '        throw "The Availability Address Space $ForestName configuration conflicts with its backup after removal. Review manually."',
                '    } else {',
                '        $state.RemovalAttempted = $false',
                '    }',
                '    Save-XtapAvailabilityBackup -Path $Path -State $state',
                '}')
            foreach ($list in @($testLines, $rollbackLines)) {
                foreach ($line in $availabilityHelpers) { $list.Add($line) }
            }
            $testLines.Add("")
            $testLines.Add("# Availability Address Spaces can't be disabled. Original configuration and removal progress are saved before removal.")
            $rollbackLines.Add("")
            $rollbackLines.Add("# Availability Address Spaces")
            foreach ($row in $aasRows) {
                $safeName = ConvertTo-CalendarDiagnosticFileNameStem -Value $row.ForestName
                $backupName = "AvailabilityAddressSpaceBackup_$safeName.json"
                $backupLiteral = "(Join-Path -Path `$PSScriptRoot -ChildPath $(ConvertTo-XtapLiteral -Value $backupName))"
                $testLines.Add("Update-XtapAvailabilityAddressSpace -Path $backupLiteral -ForestName $(ConvertTo-XtapLiteral -Value $row.ForestName)$orgArg")
                $rollbackLines.Add("Update-XtapAvailabilityAddressSpace -Restore -Path $backupLiteral -ForestName $(ConvertTo-XtapLiteral -Value $row.ForestName)$orgArg")
            }
        }

        if ($disablePolicies.Count -gt 0) {
            foreach ($list in @($testLines, $rollbackLines, $cleanupLines)) { $list.Add(""); $list.Add("# Sharing Policies") }
            foreach ($name in $disablePolicies) {
                $nameLiteral = ConvertTo-XtapLiteral -Value $name
                $hasWildcardRule = @($allSharingRows | Where-Object { $_.SharingPolicy -eq $name -and $_.RuleType -eq "Wildcard" }).Count -gt 0
                $prefix = ""
                if ($hasWildcardRule) {
                    $testLines.Add("# Wildcard rules also cover on-premises and hybrid recipients, which XTAP cannot replace. Keep this policy enabled unless you confirm no such dependencies remain.")
                    $testLines.Add("# Calendar sharing can be tested while this policy stays enabled. Only deliberately uncomment the next command after confirming all dependencies.")
                    $cleanupLines.Add("# Do not remove this wildcard policy if on-premises or hybrid sharing still depends on it.")
                    $prefix = "# "
                }
                $testLines.Add("${prefix}Set-SharingPolicy -Identity $nameLiteral -Enabled `$false$orgArg")
                $rollbackLines.Add("Set-SharingPolicy -Identity $nameLiteral -Enabled `$true$orgArg")
                $cleanupLines.Add("# Keep Sharing Policy '$(ConvertTo-XtapComment -Value $name)' disabled until all mailbox assignments have been removed or reassigned.")
                $cleanupLines.Add("# If this is the default Sharing Policy, select a replacement default policy before removal. Verify the replacement preserves the intended sharing restrictions.")
                $cleanupLines.Add("# Only remove this policy after confirming no mailboxes remain assigned to it and it is no longer the default.")
                $cleanupLines.Add("# Remove-SharingPolicy -Identity $nameLiteral -Confirm:`$true$orgArg")
            }
        }

        foreach ($name in $partialPolicies) {
            $testLines.Add("")
            $testLines.Add("# Not disabled: Sharing Policy '$(ConvertTo-XtapComment -Value $name)' has rules that can't move to XTAP yet (for example ContactsSharing). Disabling it would stop those rules.")
        }

        foreach ($line in @(
                '',
                '# Remove only the new capabilities recorded by Part 2, never a whole partner policy or unrelated capability.',
                'foreach ($entry in $capabilitiesToRemove) {',
                '    if ($entry.PartnerTenantId -eq "default") {',
                '        Remove-MgPolicyCrossTenantAccessPolicyDefaultM365Capability -M365CapabilityBaseName $entry.CreatedName -Confirm:$false -ErrorAction Stop',
                '    } else {',
                '        Remove-MgPolicyCrossTenantAccessPolicyPartnerM365Capability -CrossTenantAccessPolicyConfigurationPartnerTenantId $entry.PartnerTenantId -M365CapabilityBaseName $entry.CreatedName -Confirm:$false -ErrorAction Stop',
                '    }',
                '}',
                '$script:migrationState.RollbackCompleted = $true',
                'Save-XtapMigrationState')) {
            $rollbackLines.Add($line)
        }
        if ($hasLegacyTestCommands) {
            $scripts["XTAP_Part3_DisableForTesting.ps1"] = $testLines -join "`r`n"
        }
        $scripts["XTAP_Part3_Rollback.ps1"] = $rollbackLines -join "`r`n"
        if ($disableOrgRows.Count + $sharingOnlyOrgRows.Count + $disablePolicies.Count -gt 0) {
            $scripts["XTAP_Part4_Cleanup.ps1"] = $cleanupLines -join "`r`n"
        }
    }

    return $scripts
}
